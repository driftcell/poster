/** sender_hash（hex）→ 如 "毛茸茸山雀 #42"，同一哈希永远得到同一个名字 */
export function pseudonymFor(senderHash: string): string {
	const adjective = ADJECTIVES[parseInt(senderHash.slice(0, 2), 16) % ADJECTIVES.length];
	const noun = NOUNS[parseInt(senderHash.slice(2, 4), 16) % NOUNS.length];
	const num = parseInt(senderHash.slice(4, 6), 16) % 100;
	return `${adjective}${noun} #${num}`;
}
